"""Builds the zero-advance font that collapses hidden markup (src/editor/features/hidden-font.ts).

Every code point maps (cmap format 13) to one empty glyph with zero advance, so hidden text keeps
its place in the DOM and the accessibility tree, has real line metrics (caret, coordsAtPos,
posAtCoords), and no width. Run with fontTools 4.x:  python3 scripts/make-hidden-font.py
"""

import base64
import io
import pathlib

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib.tables._c_m_a_p import CmapSubtable

UPM = 1000
# Smaller than common text fonts, so the hidden inline box never grows a line.
ASCENT, DESCENT = 800, 200

fb = FontBuilder(UPM, isTTF=True)
fb.setupGlyphOrder([".notdef", "blank"])
fb.setupCharacterMap({0x20: "blank"})
empty = TTGlyphPen(None).glyph()
fb.setupGlyf({".notdef": empty, "blank": empty})
fb.setupHorizontalMetrics({".notdef": (0, 0), "blank": (0, 0)})
fb.setupHorizontalHeader(ascent=ASCENT, descent=-DESCENT)
fb.setupNameTable({"familyName": "TheoNotesHidden", "styleName": "Regular"})
fb.setupOS2(
    version=4, sTypoAscender=ASCENT, sTypoDescender=-DESCENT, sTypoLineGap=0,
    usWinAscent=ASCENT, usWinDescent=DESCENT, fsSelection=0x40 | 0x80,
)
fb.setupPost()

everything = {cp: "blank" for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF}
tables = []
for platform, encoding in ((0, 6), (3, 10)):
    sub = CmapSubtable.newSubtable(13)
    sub.platformID, sub.platEncID, sub.language = platform, encoding, 0
    sub.cmap = everything
    tables.append(sub)
fb.font["cmap"].tables = tables

# Fixed head.created/modified (seconds since 1904-01-01, the values of the committed font), so
# regenerating gives the same bytes; TTFont would otherwise stamp the save time.
TIMESTAMP = 3875534936
fb.font["head"].created = fb.font["head"].modified = TIMESTAMP
fb.font.recalcTimestamp = False

buf = io.BytesIO()
fb.font.save(buf)
data = base64.b64encode(buf.getvalue()).decode()
out = pathlib.Path(__file__).resolve().parent.parent / "src/editor/features/hidden-font.ts"
out.write_text(
    "// Generated by scripts/make-hidden-font.py: every code point → one empty glyph, zero advance.\n"
    f'export const hiddenFontBase64 =\n  "{data}";\n'
)
print(f"{len(buf.getvalue())} bytes → {out}")
